#ifndef SH2_TEST_BOOT_IMAGE_H
#define SH2_TEST_BOOT_IMAGE_H

#include <stdint.h>

/* Self-authored program with reset vectors, a GBR load, delayed call and
 * return, a word store, and a signed byte load. */
static const uint8_t boot_image[128] = {
    [3] = 0x10, [7] = 0x3C,
    [0x10] = 0xD1, 0x07, 0x41, 0x1E, 0xE2, 0x80, 0xB0, 0x03,
    [0x18] = 0x72, 0x01, 0x21, 0x21, 0xC4, 0x03, 0x00, 0x09,
    [0x20] = 0x72, 0x20, 0x00, 0x0B, 0x72, 0x01,
    [0x33] = 0x38,
    [0x3B] = 0xFF,
    [0x40] = 0x61, 0x21, /* mov.w @r2,r1 */
    0x63, 0x25,          /* mov.w @r2+,r3 */
    0x62, 0x25,          /* mov.w @r2+,r2 */
    0x64, 0x3d,          /* extu.w r3,r4 */
    0x24, 0x29,          /* and r2,r4 */
    0x60, 0x18,          /* swap.b r1,r0 */
    0xcb, 0x40,          /* or #0x40,r0 */
    0xc0, 0x03,          /* mov.b r0,@(3,gbr) */
    0x27, 0x02,          /* mov.l r0,@r7 */
    0x30, 0x42,          /* cmp/hs r4,r0 */
    0x45, 0x01,          /* shlr r5 */
    0x45, 0x10,          /* dt r5 */
    0x81, 0x72,          /* mov.w r0,@(4,r7) */
    0x90, 0x01,          /* mov.w @(2,pc),r0 */
    0x80, 0x73,          /* mov.b r0,@(3,r7) */
    [0x60] = 0x80, 0x03, 0xfa, 0x01
};

#endif
